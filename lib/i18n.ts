export function normalizeLocale(value?: string | null): Locale {
  return value === "pl" ? "pl" : "en";
}

export function getDictionary(locale?: string | null) {
  return dictionaries[normalizeLocale(locale)];
}

export async function getUserDictionary(userId: string) {
  const user = await prisma.user.findUnique({ where: { id: userId }, select: { language: true } });
  return getDictionary(user?.language);
}
